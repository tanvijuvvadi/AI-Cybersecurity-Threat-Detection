def clean(df):
    before = len(df)
    df = df.drop_duplicates().replace([np.inf, -np.inf], np.nan).dropna().reset_index(drop=True)
    print(f"Cleaning: {before:,} -> {len(df):,} rows")
    return df

def add_features(df):
    df = df.copy()
    df["bytes_per_packet"] = (df["src_bytes"] + df["dst_bytes"]) / df["packets"].clip(lower=1)
    df["byte_ratio"] = df["src_bytes"] / (df["dst_bytes"] + 1)
    df["packets_per_sec"] = df["packets"] / (df["duration"] + 0.01)
    df["login_fail_rate"] = df["failed_logins"] / (df["conn_count_60s"] + 1)
    df["port_spread"] = df["unique_dst_ports"] / (df["conn_count_60s"] + 1)
    df["log_src_bytes"] = np.log1p(df["src_bytes"])
    df["log_dst_bytes"] = np.log1p(df["dst_bytes"])
    return df

ID_COLS, TARGETS = ["timestamp", "src_ip", "dst_ip"], ["attack_type", "label"]

def split_xy(df, target="label"):
    """Model inputs only: IPs/timestamps removed so the model learns behaviour, not addresses."""
    return df.drop(columns=[c for c in ID_COLS + TARGETS if c in df.columns]), df[target]

def make_pipeline(X, estimator):
    cat = X.select_dtypes(exclude="number").columns.tolist()
    num = [c for c in X.columns if c not in cat]
    prep = ColumnTransformer([("num", StandardScaler(), num), ("cat", OneHotEncoder(handle_unknown="ignore"), cat)])
    return Pipeline([("prep", prep), ("model", estimator)])

