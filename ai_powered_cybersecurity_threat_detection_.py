def severity(p):
    return "CRITICAL" if p >= 0.95 else "HIGH" if p >= 0.80 else "MEDIUM" if p >= 0.50 else "LOW"

def evidence(r):   # human-readable reasons, like a SOC analyst's ticket
    e = []
    if r["failed_logins"] >= 5: e.append(f"{int(r['failed_logins'])} failed logins")
    if r["request_rate"] > 100: e.append(f"request rate {r['request_rate']:.0f}/s")
    if r["unique_dst_ports"] > 20: e.append(f"{int(r['unique_dst_ports'])} ports probed")
    if r["syn_ratio"] > 0.7: e.append(f"SYN ratio {r['syn_ratio']:.2f}")
    return "; ".join(e) if e else "statistical deviation from normal profile"

def detect_threats(df, threshold=0.5):
    X, _ = split_xy(df)
    out = df.copy()
    out["threat_score"] = rf.predict_proba(X)[:, 1]
    out["predicted_type"] = type_clf.predict(X)
    out["iso_anomaly"] = iso.predict(X) == -1
    known = out["threat_score"] >= threshold
    unknown = (~known) & out["iso_anomaly"]          # RF says normal but behaviour is odd -> zero-day suspect
    alerts = out[known | unknown].copy()
    alerts["alert_type"] = alerts["predicted_type"].where(known[alerts.index], "Unknown Anomaly")
    alerts["alert_type"] = alerts["alert_type"].replace("Normal", "Unclassified Threat")
    alerts["severity"] = [severity(p) if k else "LOW" for p, k in zip(alerts["threat_score"], known[alerts.index])]
    alerts["evidence"] = alerts.apply(evidence, axis=1)
    return alerts.sort_values("timestamp").reset_index(drop=True), out

